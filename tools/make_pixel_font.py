def build(out: Path) -> None:
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.ttGlyphPen import TTGlyphPen

    names = {ch: ("space" if ch == " " else f"uni{ord(ch):04X}") for ch in G}
    order = [".notdef"] + [names[ch] for ch in G]
    glyphs, metrics = {}, {}

    # .notdef: hollow box
    pen = TTGlyphPen(None)
    for x0, y0, x1, y1 in ((0, 0, 5, 1), (0, 6, 5, 7), (0, 1, 1, 6), (4, 1, 5, 6)):
        _rect(pen, x0, y0, x1, y1)
    glyphs[".notdef"] = pen.glyph()
    metrics[".notdef"] = (ADVANCE * DOT, 0)

    for ch, rows in G.items():
        pen = TTGlyphPen(None)
        min_x = None
        for r, row in enumerate(rows):
            y_top = 7 - r              # row 0 occupies dots 6..7 above the baseline, row 7 dots -1..0
            c = 0
            while c < len(row):        # merge horizontal runs into one rectangle
                if row[c] == "#":
                    start = c
                    while c < len(row) and row[c] == "#":
                        c += 1
                    _rect(pen, start, y_top - 1, c, y_top)
                    min_x = start if min_x is None else min(min_x, start)
                else:
                    c += 1
        glyphs[names[ch]] = pen.glyph()
        metrics[names[ch]] = (ADVANCE * DOT, (min_x or 0) * DOT)

    fb = FontBuilder(8 * DOT, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({ord(ch): names[ch] for ch in G})
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    ascent, descent = 9 * DOT, 2 * DOT   # 1 dot of space above capitals, 1 below descenders
    fb.setupHorizontalHeader(ascent=ascent, descent=-descent)
    fb.setupNameTable({"familyName": "RetroRAG Phosphor", "styleName": "Regular",
                       "copyright": "RetroRAG project - original pixel font, free to use with RetroRAG",
                       "uniqueFontIdentifier": "RetroRAG Phosphor Regular", "fullName": "RetroRAG Phosphor",
                       "psName": "RetroRAGPhosphor-Regular", "version": "Version 1.000"})
    fb.setupOS2(sTypoAscender=ascent, sTypoDescender=-descent, sTypoLineGap=0, usWinAscent=ascent,
                usWinDescent=descent, xAvgCharWidth=ADVANCE * DOT, achVendID="RRAG", fsType=0,
                sxHeight=5 * DOT, sCapHeight=7 * DOT)
    fb.setupPost(isFixedPitch=1)
    out.parent.mkdir(parents=True, exist_ok=True)
    fb.save(str(out))


def _rect(pen, x0, y0, x1, y1):
    """Clockwise rectangle in dot units (TrueType outer contour)."""
    pen.moveTo((x0 * DOT, y0 * DOT))
    pen.lineTo((x0 * DOT, y1 * DOT))
    pen.lineTo((x1 * DOT, y1 * DOT))
    pen.lineTo((x1 * DOT, y0 * DOT))
    pen.closePath()


